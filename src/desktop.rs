//! Desktop entry discovery and rendering. Source text is read one application at a
//! time; existing groups and actions are preserved when adding recent entries.

use crate::{Result, history::Recent, paths::Paths, storage::walk};
use freedesktop_desktop_entry::{Line, parse_line};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
};

const MARKER: &str = "# Generated by xdg-recent-actions; edit the original entry, not this file.";
/// Compact identity and source location for one visible application.
#[derive(Clone, Debug)]
pub(crate) struct App {
    pub(crate) id: String,
    pub(crate) source: PathBuf,
    pub(crate) name: String,
    pub(crate) executable: String,
}
/// Read only the main group keys required for discovery and action rendering.
fn desktop_keys(text: &str) -> Result<BTreeMap<&str, &str>> {
    let mut main = false;
    let mut keys = BTreeMap::new();
    for line in text.lines() {
        match parse_line(line.trim())? {
            Line::Group(group) => main = group == "Desktop Entry",
            Line::Entry(key, value) if main => {
                let key = key.trim();
                if matches!(
                    key,
                    "Type" | "Hidden" | "NoDisplay" | "Exec" | "Name" | "Actions"
                ) {
                    keys.insert(key, value.trim());
                }
            }
            _ => {}
        }
    }
    Ok(keys)
}
/// Normalize a display name or desktop ID for identity matching.
pub(crate) fn normalized(s: &str) -> String {
    s.trim_end_matches(".desktop").to_lowercase()
}
/// Extract a command basename, accepting GTK quoting when reading XBEL commands.
pub(crate) fn executable(command: &str, xbel: bool) -> Option<String> {
    let mut words = shlex::split(command)?;
    // GTK stores the entire command as one shell-quoted argument.
    if xbel && words.len() == 1 {
        words = shlex::split(&words[0])?;
    }
    let mut it = words.iter();
    let mut word = it.next()?;
    if Path::new(word).file_name()?.to_str()? == "env" {
        word = it.find(|w| !w.contains('=') && !w.starts_with('-'))?;
    }
    Some(Path::new(word).file_name()?.to_str()?.to_owned())
}
/// Discover visible applications in XDG precedence order, retaining compact metadata.
/// Owned launchers use their saved original or the lower-priority vendor entry.
pub(crate) fn inventory(paths: &Paths) -> Result<Vec<App>> {
    let mut seen = BTreeSet::new();
    let mut apps = Vec::new();
    for (i, root) in paths.roots.iter().enumerate() {
        let mut files = Vec::new();
        walk(root, root, &mut files)?;
        if i == 0 {
            // A backup can outlive the link if a write was interrupted.
            let mut backups = Vec::new();
            walk(
                &paths.managed.join("originals"),
                &paths.managed.join("originals"),
                &mut backups,
            )?;
            for (id, file) in backups {
                if fs::symlink_metadata(paths.target(&id)).is_err() {
                    files.push((id, file));
                }
            }
        }
        for (id, file) in files {
            if seen.contains(&id) {
                continue;
            }
            let source = if i == 0 && paths.owns(&id) {
                if paths.original(&id).is_file() {
                    paths.original(&id)
                } else {
                    continue;
                }
            } else {
                file
            };
            let text = fs::read_to_string(&source)?;
            seen.insert(id.clone()); // Hidden entries also mask lower-priority entries.
            let k = desktop_keys(&text)?;
            if k.get("Type").is_none_or(|v| *v != "Application")
                || ["Hidden", "NoDisplay"]
                    .iter()
                    .any(|key| k.get(*key).is_some_and(|v| *v == "true"))
            {
                continue;
            }
            let Some(exec) = k.get("Exec").and_then(|s| executable(s, false)) else {
                continue;
            };
            apps.push(App {
                id,
                name: normalized(k.get("Name").copied().unwrap_or("")),
                executable: exec,
                source,
            });
        }
    }
    Ok(apps)
}
/// Escape a desktop entry string value.
fn value(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}
/// Quote one Desktop Entry Exec argument, including reserved characters and percent signs.
fn exec_arg(s: &str) -> String {
    // Desktop Entry string unescaping happens BEFORE Exec argument unquoting.
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '%' => out.push_str("%%"),
            '\\' => out.push_str("\\\\\\\\"),
            '"' | '$' | '`' => {
                out.push_str("\\\\");
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}
/// Add recent actions while preserving existing groups and avoiding action ID collisions.
pub(crate) fn render(text: &str, recents: &[Recent], target: &Path, gio: &Path) -> Result<String> {
    let keys = desktop_keys(text)?;
    let old = keys.get("Actions").copied().unwrap_or_default();
    let mut used = BTreeSet::new();
    for line in text.lines() {
        if let Line::Group(group) = parse_line(line.trim())?
            && let Some(id) = group.strip_prefix("Desktop Action ")
        {
            used.insert(id.to_owned());
        }
    }
    let mut ids = Vec::new();
    for _ in recents {
        let mut n = ids.len();
        loop {
            let id = format!("XdgRecent{n}");
            if used.insert(id.clone()) {
                ids.push(id);
                break;
            }
            n += 1;
        }
    }
    let actions = format!(
        "{}{}{};",
        old,
        if old.is_empty() || old.ends_with(';') {
            ""
        } else {
            ";"
        },
        ids.join(";")
    );
    let mut out = String::new();
    let mut main = false;
    let mut inserted = false;
    for line in text.lines() {
        let parsed = parse_line(line.trim())?;
        if let Line::Group(group) = parsed {
            if main && !inserted {
                out.push_str(&format!("Actions={actions}\n"));
                inserted = true;
            }
            main = group == "Desktop Entry";
        }
        if main && matches!(parsed, Line::Entry(key, _) if key.trim() == "Actions") {
            if !inserted {
                out.push_str(&format!("Actions={actions}\n"));
                inserted = true;
            }
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    if !inserted {
        out.push_str(&format!("Actions={actions}\n"));
    }
    out.push_str(&format!("\n{MARKER}\n"));
    for (id, recent) in ids.iter().zip(recents) {
        // gio handles original Exec field codes, working directory and Terminal flags.
        let label = recent
            .path
            .file_name()
            .unwrap_or(recent.path.as_os_str())
            .to_string_lossy();
        let parent = recent
            .path
            .parent()
            .unwrap_or(Path::new("/"))
            .to_string_lossy();
        out.push_str(&format!(
            "\n[Desktop Action {id}]\nName=Recent: {} ({})\nExec={} launch {} {}\n",
            value(&label),
            value(&parent),
            exec_arg(gio.to_str().ok_or("non-UTF8 gio path")?),
            exec_arg(target.to_str().ok_or("non-UTF8 desktop path")?),
            exec_arg(&recent.uri)
        ));
    }
    Ok(out)
}

