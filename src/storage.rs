//! Atomic publication and restoration of desktop entries. Filenames identify saved
//! originals; launcher symlinks prove ownership. Unchanged output is not rewritten.

use crate::{Result, paths::Paths};
use std::{
    collections::BTreeSet,
    fs::{self, File},
    io::{BufRead, BufReader, Read, Write},
    os::unix::fs::{PermissionsExt, symlink},
    path::{Path, PathBuf},
};

/// Read UTF-8 text; only a missing file becomes `None`.
fn read_optional(path: &Path) -> Result<Option<String>> {
    match fs::read_to_string(path) {
        Ok(s) => Ok(Some(s)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}
/// Collect desktop filenames recursively, converting relative paths to desktop IDs.
pub(crate) fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) -> Result<()> {
    if !dir.exists() {
        return Ok(());
    }
    for entry in walkdir::WalkDir::new(dir).min_depth(1).sort_by_file_name() {
        let entry = entry?;
        let path = entry.path();
        if !entry.file_type().is_dir() && path.extension().is_some_and(|s| s == "desktop") {
            let id = path
                .strip_prefix(root)?
                .components()
                .map(|s| s.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("-");
            out.push((id, path.to_owned()));
        }
    }
    Ok(())
}
/// Write and sync a sibling temporary file, then rename it over the destination.
fn atomic(path: &Path, contents: &str, mode: u32) -> Result<()> {
    let parent = path.parent().ok_or("missing parent")?;
    fs::create_dir_all(parent)?;
    let mut file = tempfile::NamedTempFile::new_in(parent)?;
    file.as_file()
        .set_permissions(fs::Permissions::from_mode(mode))?;
    file.write_all(contents.as_bytes())?;
    file.as_file().sync_all()?;
    file.persist(path)?;
    File::open(parent)?.sync_all()?;
    Ok(())
}
/// Compare size and streaming checksums so identical output keeps its inode and timestamp.
fn same_output(path: &Path, output: &[u8]) -> Result<bool> {
    let file = match File::open(path) {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => return Err(e.into()),
    };
    if file.metadata()?.len() != output.len() as u64 {
        return Ok(false);
    }
    let mut checksum = blake3::Hasher::new();
    checksum.update_reader(file)?;
    Ok(checksum.finalize() == blake3::hash(output))
}
/// Compare files with fixed-size buffers without retaining their contents.
fn files_equal(left: &Path, right: &Path) -> Result<bool> {
    if fs::metadata(left)?.len() != fs::metadata(right)?.len() {
        return Ok(false);
    }
    let mut a = BufReader::new(File::open(left)?);
    let mut b = BufReader::new(File::open(right)?);
    let mut bytes = [0; 8192];
    loop {
        let n = a.read(&mut bytes)?;
        if n == 0 {
            return Ok(b.fill_buf()?.is_empty());
        }
        let mut other = [0; 8192];
        b.read_exact(&mut other[..n])?;
        if bytes[..n] != other[..n] {
            return Ok(false);
        }
    }
}
/// Save an existing user entry once before replacing it; never back up generated output.
fn backup_original(paths: &Paths, id: &str) -> Result<()> {
    let original = paths.original(id);
    if original.exists() {
        return Ok(());
    }
    let source = paths.target(id);
    if !source.exists() {
        return Ok(());
    }
    fs::create_dir_all(original.parent().unwrap())?;
    let mut input = File::open(&source)?;
    let mut output = tempfile::NamedTempFile::new_in(original.parent().unwrap())?;
    output
        .as_file()
        .set_permissions(input.metadata()?.permissions())?;
    std::io::copy(&mut input, &mut output)?;
    output.as_file().sync_all()?;
    output.persist_noclobber(&original)?;
    File::open(original.parent().unwrap())?.sync_all()?;
    Ok(())
}
/// Publish generated text and an owned launcher symlink, unless output is unchanged.
/// Dry runs report changes without writing. Refuse unowned symlinks or conflicting originals.
pub(crate) fn publish(paths: &Paths, id: &str, output: &str, dry: bool) -> Result<bool> {
    let owned = paths.owns(id);
    let target = paths.target(id);
    if !owned {
        if target.is_symlink() {
            return Err(format!("{id}: existing symlink belongs to someone else").into());
        }
        if let Some(current) = read_optional(&target)? {
            if paths.original(id).exists() {
                if !files_equal(&target, &paths.original(id))? {
                    return Err(
                        format!("{id}: target was replaced; original backup retained").into(),
                    );
                }
            } else if current.contains("# Generated by xdg-recent-actions;") {
                return Err(format!(
                    "{id}: unowned generated entry; refusing to back up generated output"
                )
                .into());
            }
        }
    }
    let changed = !same_output(&paths.generated(id), output.as_bytes())?;
    if !dry {
        if changed {
            atomic(&paths.generated(id), output, 0o600)?;
        }
        if !owned {
            backup_original(paths, id)?;
            fs::create_dir_all(target.parent().unwrap())?;
            let staging = tempfile::tempdir_in(target.parent().unwrap())?;
            let link = staging.path().join("launcher");
            symlink(paths.link(id), &link)?;
            fs::rename(&link, &target)?;
            File::open(target.parent().unwrap())?.sync_all()?;
        }
    }
    Ok(changed || !owned)
}
/// Find managed IDs from generated files, originals, and owned launcher symlinks.
pub(crate) fn managed_ids(paths: &Paths) -> Result<BTreeSet<String>> {
    let mut ids = BTreeSet::new();
    for dir in [
        paths.managed.join("generated"),
        paths.managed.join("originals"),
    ] {
        let mut files = Vec::new();
        walk(&dir, &dir, &mut files)?;
        ids.extend(files.into_iter().map(|(id, _)| id));
    }
    let mut files = Vec::new();
    walk(
        &paths.data.join("applications"),
        &paths.data.join("applications"),
        &mut files,
    )?;
    ids.extend(
        files
            .into_iter()
            .filter_map(|(id, _)| paths.owns(&id).then_some(id)),
    );
    Ok(ids)
}
/// Restore an original or remove an owned launcher. Preserve unknown replacements.
/// Also handle publication interrupted between saving the original and linking the launcher.
pub(crate) fn restore_one(paths: &Paths, id: &str, dry: bool) -> Result<()> {
    let target = paths.target(id);
    let original = paths.original(id);
    if paths.owns(id) || fs::symlink_metadata(&target).is_err() {
        if !dry {
            if original.exists() {
                fs::create_dir_all(target.parent().unwrap())?;
                fs::rename(&original, &target)?;
            } else if target.is_symlink() {
                fs::remove_file(&target)?;
            }
        }
    } else if original.exists() {
        if target.is_symlink() || !files_equal(&target, &original)? {
            return Err(format!(
                "{id}: replacement entry left untouched; original retained at {}",
                original.display()
            )
            .into());
        }
        if !dry {
            fs::remove_file(&original)?;
        }
    }
    if !dry {
        match fs::remove_file(paths.generated(id)) {
            Ok(()) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(e.into()),
        }
    }
    Ok(())
}
