type Result<T> = std::result::Result<T, Box<dyn Error>>;
const LIMIT: usize = 8;
const MARKER: &str = "# Generated by xdg-recent-actions; see its state directory before editing.";

#[derive(Clone)]
struct Paths {
    data: PathBuf,
    roots: Vec<PathBuf>,
    state: PathBuf,
}
impl Paths {
    fn from_env() -> Result<Self> {
        let home = PathBuf::from(env::var_os("HOME").ok_or("HOME is unset")?);
        let data = env::var_os("XDG_DATA_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| home.join(".local/share"));
        let state = env::var_os("XDG_STATE_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| home.join(".local/state"));
        let mut roots = vec![data.join("applications")];
        roots.extend(
            env::split_paths(
                &env::var_os("XDG_DATA_DIRS")
                    .unwrap_or_else(|| "/usr/local/share:/usr/share".into()),
            )
            .filter(|p| p.is_absolute())
            .map(|p| p.join("applications")),
        );
        if !data.is_absolute() || !state.is_absolute() {
            return Err("XDG data/state paths must be absolute".into());
        }
        Ok(Self {
            data,
            roots,
            state: state.join("xdg-recent-actions"),
        })
    }
    fn target(&self, id: &str) -> PathBuf {
        self.data.join("applications").join(id)
    }
}

#[derive(Default, Serialize, Deserialize)]
struct State {
    version: u32,
    entries: BTreeMap<String, bool>,
    #[serde(skip)]
    legacy: BTreeMap<String, Managed>,
}
#[derive(Clone, Serialize, Deserialize)]
struct Managed {
    // None means we created an override; Some preserves a pre-existing user entry.
    original: Option<String>,
    #[serde(default)]
    original_mode: Option<u32>,
    generated: String,
    // Journal the prior content before an atomic replacement, for crash recovery.
    previous: Option<String>,
}
#[derive(Clone, Debug)]
struct App {
    id: String,
    source: Option<PathBuf>,
    name: String,
    executable: String,
}
#[derive(Clone, Debug)]
struct Recent {
    uri: String,
    path: PathBuf,
}

fn desktop_keys(text: &str) -> BTreeMap<String, String> {
    let mut main = false;
    let mut keys = BTreeMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            main = line == "[Desktop Entry]";
        } else if main
            && !line.starts_with('#')
            && let Some((k, v)) = line.split_once('=')
        {
            let key = k.trim();
            if matches!(
                key,
                "Type" | "Hidden" | "NoDisplay" | "Exec" | "Name" | "Actions"
            ) {
                keys.insert(key.into(), v.trim().into());
            }
        }
    }
    keys
}
fn normalized(s: &str) -> String {
    s.trim_end_matches(".desktop").to_lowercase()
}
fn executable(command: &str, xbel: bool) -> Option<String> {
    let mut words = shlex::split(command)?;
    // GTK stores the entire command as one shell-quoted argument.
    if xbel && words.len() == 1 {
        words = shlex::split(&words[0])?;
    }
    let mut it = words.iter();
    let mut word = it.next()?;
    if Path::new(word).file_name()?.to_str()? == "env" {
        word = it.find(|w| !w.contains('=') && !w.starts_with('-'))?;
    }
    Some(Path::new(word).file_name()?.to_str()?.to_owned())
}
fn read_optional(path: &Path) -> Result<Option<String>> {
    match fs::read_to_string(path) {
        Ok(s) => Ok(Some(s)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}
fn walk(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) -> Result<()> {
    if !dir.exists() {
        return Ok(());
    }
    let mut entries = fs::read_dir(dir)?.collect::<std::result::Result<Vec<_>, _>>()?;
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            walk(root, &path, out)?;
        } else if path.extension().is_some_and(|s| s == "desktop") {
            let id = path
                .strip_prefix(root)?
                .components()
                .map(|s| s.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("-");
            out.push((id, path));
        }
    }
    Ok(())
}
fn inventory(paths: &Paths, state: &State) -> Result<Vec<App>> {
    let mut seen = BTreeSet::new();
    let mut apps = Vec::new();
    for (i, root) in paths.roots.iter().enumerate() {
        let mut files = Vec::new();
        walk(root, root, &mut files)?;
        for (id, file) in files {
            if seen.contains(&id) {
                continue;
            }
            let mut source = Some(file.clone());
            let text = if i == 0 {
                if let Some(has_original) = state.entries.get(&id) {
                    if !has_original {
                        continue;
                    }
                    source = None;
                    managed(paths, state, &id)?
                        .ok_or("missing ownership record")?
                        .original
                        .ok_or("missing original desktop entry")?
                } else {
                    fs::read_to_string(&file)?
                }
            } else {
                fs::read_to_string(&file)?
            };
            seen.insert(id.clone()); // Hidden entries also mask lower-priority entries.
            let k = desktop_keys(&text);
            if k.get("Type").is_none_or(|v| v != "Application")
                || ["Hidden", "NoDisplay"]
                    .iter()
                    .any(|key| k.get(*key).is_some_and(|v| v == "true"))
            {
                continue;
            }
            let Some(exec) = k.get("Exec").and_then(|s| executable(s, false)) else {
                continue;
            };
            apps.push(App {
                id,
                name: normalized(k.get("Name").map(String::as_str).unwrap_or("")),
                executable: exec,
                source,
            });
        }
    }
    Ok(apps)
}
#[derive(Clone, Copy, Debug)]
struct Pin {
    offset: u64,
    length: u64,
    modified: i64,
    identity: u64,
}
fn bookmarks(
    input: impl BufRead,
    mut emit: impl FnMut(&str, &str, &str, Pin) -> Result<()>,
) -> Result<()> {
    let mut reader = Reader::from_reader(input);
    let mut buffer = Vec::with_capacity(4096);
    let mut uri = None;
    let mut depth = 0usize;
    let mut root_seen = false;
    loop {
        let offset = reader.buffer_position();
        let event = reader.read_event_into(&mut buffer)?;
        let length = reader.buffer_position() - offset;
        let empty = matches!(event, Event::Empty(_));
        match event {
            Event::Start(e) | Event::Empty(e) => {
                let local = e.local_name();
                if depth == 0 {
                    if local.as_ref() != b"xbel" || root_seen {
                        return Err("expected one XBEL root".into());
                    }
                    root_seen = true;
                }
                let mut href = std::borrow::Cow::Borrowed("");
                let mut name = std::borrow::Cow::Borrowed("");
                let mut exec = std::borrow::Cow::Borrowed("");
                let mut modified = std::borrow::Cow::Borrowed("");
                for attr in e.attributes() {
                    let attr = attr?;
                    let value = attr.decode_and_unescape_value(reader.decoder())?;
                    match attr.key.local_name().as_ref() {
                        b"href" => href = value,
                        b"name" => name = value,
                        b"exec" => exec = value,
                        b"modified" => modified = value,
                        _ => {}
                    }
                }
                if local.as_ref() == b"bookmark" {
                    uri = Url::parse(&href)
                        .ok()
                        .filter(|url| url.scheme() == "file")
                        .filter(|url| url.to_file_path().is_ok_and(|path| path.exists()))
                        .map(|url| (url.to_string(), offset, length));
                }
                if local.as_ref() == b"application"
                    && let Some((uri, offset, length)) = &uri
                {
                    let modified = chrono::DateTime::parse_from_rfc3339(&modified)
                        .ok()
                        .map(|t| t.timestamp_micros())
                        .unwrap_or(i64::MIN);
                    let pin = Pin {
                        offset: *offset,
                        length: *length,
                        modified,
                        identity: fingerprint(uri),
                    };
                    emit(uri, &name, &exec, pin)?;
                }
                if !empty {
                    depth += 1;
                } else if local.as_ref() == b"bookmark" {
                    uri = None;
                }
            }
            Event::End(e) => {
                depth = depth.checked_sub(1).ok_or("invalid XML depth")?;
                if e.local_name().as_ref() == b"bookmark" {
                    uri = None;
                }
            }
            Event::Text(t) if depth == 0 && !t.decode()?.trim().is_empty() => {
                return Err("text outside XBEL root".into());
            }
            Event::Eof => break,
            _ => {}
        }
        buffer.clear();
    }
    if !root_seen || depth != 0 {
        return Err("incomplete XBEL document; leaving actions unchanged".into());
    }
    Ok(())
}

fn fingerprint(uri: &str) -> u64 {
    uri.bytes().fold(0xcbf29ce484222325, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x100000001b3)
    })
}
fn read_pin(file: &File, pin: Pin) -> Result<Recent> {
    let mut bytes = vec![0; usize::try_from(pin.length)?];
    file.read_exact_at(&mut bytes, pin.offset)?;
    let mut reader = Reader::from_reader(bytes.as_slice());
    let event = reader.read_event()?;
    let element = match event {
        Event::Start(e) | Event::Empty(e) if e.local_name().as_ref() == b"bookmark" => e,
        _ => return Err("history changed during scan".into()),
    };
    let mut uri = None;
    for attr in element.attributes() {
        let attr = attr?;
        if attr.key.local_name().as_ref() == b"href" {
            uri = Some(Url::parse(
                &attr.decode_and_unescape_value(reader.decoder())?,
            )?);
        }
    }
    let url = uri.ok_or("bookmark has no href")?;
    let path = url
        .to_file_path()
        .map_err(|_| "bookmark is no longer a local file")?;
    let uri = url.to_string();
    if fingerprint(&uri) != pin.identity {
        return Err("history changed during scan".into());
    }
    Ok(Recent { uri, path })
}
fn retain_pin(file: &File, group: &mut Vec<Pin>, uri: &str, pin: Pin) -> Result<()> {
    // Hashes limit positional reads; compare actual URIs before treating a hash match as a duplicate.
    for i in 0..group.len() {
        if group[i].identity == pin.identity && read_pin(file, group[i])?.uri == uri {
            if group[i].modified >= pin.modified {
                return Ok(());
            }
            group.remove(i);
            break;
        }
    }
    let key = (std::cmp::Reverse(pin.modified), pin.identity);
    let position = group.partition_point(|p| (std::cmp::Reverse(p.modified), p.identity) <= key);
    if position >= LIMIT {
        return Ok(());
    }
    if group.len() == LIMIT {
        group.pop();
    }
    group.insert(position, pin);
    Ok(())
}
fn app_text<'a>(app: &App, record: Option<&'a Managed>) -> Result<std::borrow::Cow<'a, str>> {
    if let Some(path) = &app.source {
        Ok(fs::read_to_string(path)?.into())
    } else {
        Ok(record
            .and_then(|m| m.original.as_deref())
            .ok_or("missing original desktop entry")?
            .into())
    }
}

// Index both identities and executables once; never scan every app per bookmark.
struct Index {
    names: BTreeMap<String, BTreeSet<usize>>,
    executables: BTreeMap<String, BTreeSet<usize>>,
}
impl Index {
    fn new(apps: &[App]) -> Self {
        let mut index = Self {
            names: BTreeMap::new(),
            executables: BTreeMap::new(),
        };
        for (i, app) in apps.iter().enumerate() {
            for name in [normalized(&app.id), app.name.clone()] {
                index.names.entry(name).or_default().insert(i);
            }
            index
                .executables
                .entry(app.executable.clone())
                .or_default()
                .insert(i);
        }
        index
    }
    fn find(&self, recorded_name: &str, recorded_exec: &str) -> Option<usize> {
        let name = normalized(recorded_name);
        let names = self.names.get(&name);
        let command = executable(recorded_exec, true);
        let execs = command.as_ref().and_then(|e| self.executables.get(e));
        // The actual launch command takes precedence over a reporting app's name.
        if let Some(execs) = execs {
            let wrapper = command.as_deref().is_some_and(|c| {
                matches!(
                    c,
                    "sh" | "bash"
                        | "dash"
                        | "zsh"
                        | "fish"
                        | "flatpak"
                        | "snap"
                        | "python"
                        | "python3"
                        | "perl"
                        | "ruby"
                        | "node"
                        | "java"
                        | "wine"
                        | "wine64"
                        | "gio"
                        | "gtk-launch"
                        | "xdg-open"
                )
            });
            if execs.len() == 1 && !wrapper {
                return execs.first().copied();
            }
            let matches = names
                .map(|n| n.intersection(execs).copied().collect::<Vec<_>>())
                .unwrap_or_default();
            return (matches.len() == 1).then(|| matches[0]);
        }
        // Some GTK records use a desktop ID as the executable.
        let matches: BTreeSet<_> = names
            .into_iter()
            .flatten()
            .copied()
            .chain(
                command
                    .as_ref()
                    .and_then(|c| self.names.get(&normalized(c)))
                    .into_iter()
                    .flatten()
                    .copied(),
            )
            .collect();
        (matches.len() == 1).then(|| *matches.first().unwrap())
    }
}
fn value(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}
fn exec_arg(s: &str) -> String {
    // Desktop Entry string unescaping happens BEFORE Exec argument unquoting.
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '%' => out.push_str("%%"),
            '\\' => out.push_str("\\\\\\\\"),
            '"' | '$' | '`' => {
                out.push_str("\\\\");
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}
fn render(text: &str, recents: &[Recent], target: &Path, gio: &Path) -> Result<String> {
    let keys = desktop_keys(text);
    let old = keys.get("Actions").cloned().unwrap_or_default();
    let mut used: BTreeSet<String> = text
        .lines()
        .filter_map(|l| {
            l.strip_prefix("[Desktop Action ")
                .and_then(|s| s.strip_suffix(']'))
                .map(str::to_owned)
        })
        .collect();
    let mut ids = Vec::new();
    for _ in recents {
        let mut n = ids.len();
        loop {
            let id = format!("XdgRecent{n}");
            if used.insert(id.clone()) {
                ids.push(id);
                break;
            }
            n += 1;
        }
    }
    let actions = format!(
        "{}{}{};",
        old,
        if old.is_empty() || old.ends_with(';') {
            ""
        } else {
            ";"
        },
        ids.join(";")
    );
    let mut out = String::new();
    let mut main = false;
    let mut inserted = false;
    for line in text.lines() {
        if line.trim().starts_with('[') {
            if main && !inserted {
                out.push_str(&format!("Actions={actions}\n"));
                inserted = true;
            }
            main = line.trim() == "[Desktop Entry]";
        }
        if main
            && line
                .split_once('=')
                .is_some_and(|(k, _)| k.trim() == "Actions")
        {
            if !inserted {
                out.push_str(&format!("Actions={actions}\n"));
                inserted = true;
            }
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    if !inserted {
        out.push_str(&format!("Actions={actions}\n"));
    }
    out.push_str(&format!("\n{MARKER}\n"));
    for (id, recent) in ids.iter().zip(recents) {
        // gio handles original Exec field codes, working directory and Terminal flags.
        let label = recent
            .path
            .file_name()
            .unwrap_or(recent.path.as_os_str())
            .to_string_lossy();
        let parent = recent
            .path
            .parent()
            .unwrap_or(Path::new("/"))
            .to_string_lossy();
        out.push_str(&format!(
            "\n[Desktop Action {id}]\nName=Recent: {} ({})\nExec={} launch {} {}\n",
            value(&label),
            value(&parent),
            exec_arg(gio.to_str().ok_or("non-UTF8 gio path")?),
            exec_arg(target.to_str().ok_or("non-UTF8 desktop path")?),
            exec_arg(&recent.uri)
        ));
    }
    Ok(out)
}
fn atomic(path: &Path, contents: &str, mode: u32) -> Result<()> {
    let parent = path.parent().ok_or("missing parent")?;
    fs::create_dir_all(parent)?;
    let tmp = parent.join(format!(".xdg-recent-actions-{}.tmp", std::process::id()));
    let result = (|| -> Result<()> {
        let mut f = OpenOptions::new().write(true).create_new(true).open(&tmp)?;
        f.set_permissions(fs::Permissions::from_mode(mode))?;
        f.write_all(contents.as_bytes())?;
        f.sync_all()?;
        fs::rename(&tmp, path)?;
        File::open(parent)?.sync_all()?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}
fn save(paths: &Paths, state: &State) -> Result<()> {
    atomic(
        &paths.state.join("state.json"),
        &serde_json::to_string(state)?,
        0o600,
    )
}
fn record_path(paths: &Paths, id: &str) -> PathBuf {
    paths.state.join("entries").join(format!("{id}.json"))
}
fn managed(paths: &Paths, state: &State, id: &str) -> Result<Option<Managed>> {
    if let Some(m) = state.legacy.get(id) {
        return Ok(Some(m.clone()));
    }
    if !state.entries.contains_key(id) {
        return Ok(None);
    }
    Ok(Some(serde_json::from_reader(BufReader::new(File::open(
        record_path(paths, id),
    )?))?))
}
fn load(paths: &Paths, dry: bool) -> Result<State> {
    let value: serde_json::Value = match File::open(paths.state.join("state.json")) {
        Ok(file) => serde_json::from_reader(BufReader::new(file))?,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            return Ok(State {
                version: 2,
                ..State::default()
            });
        }
        Err(e) => return Err(e.into()),
    };
    let mut state: State = match value["version"].as_u64() {
        Some(2) => serde_json::from_value(value)?,
        Some(1) => {
            #[derive(Deserialize)]
            struct Legacy {
                entries: BTreeMap<String, Managed>,
            }
            let old: Legacy = serde_json::from_value(value)?;
            State {
                version: 2,
                entries: old
                    .entries
                    .iter()
                    .map(|(id, m)| (id.clone(), m.original.is_some()))
                    .collect(),
                legacy: old.entries,
            }
        }
        _ => return Err("unsupported state version; upgrade without deleting state.json".into()),
    };
    for id in state.entries.keys() {
        if id.contains('/') || !id.ends_with(".desktop") {
            return Err("invalid desktop ID in state".into());
        }
    }
    if !dry && !state.legacy.is_empty() {
        for (id, record) in &state.legacy {
            atomic(
                &record_path(paths, id),
                &serde_json::to_string(record)?,
                0o600,
            )?;
        }
        save(paths, &state)?;
        state.legacy.clear();
    }
    Ok(state)
}
fn forget(paths: &Paths, state: &mut State, id: &str) -> Result<()> {
    state.entries.remove(id);
    save(paths, state)?;
    match fs::remove_file(record_path(paths, id)) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(e.into()),
    }
    Ok(())
}
// Used by the installer before rolling back to a binary that only understands v1.
fn export_v1(paths: &Paths, state: &State) -> Result<()> {
    let tmp = paths
        .state
        .join(format!(".export-{}.tmp", std::process::id()));
    let result = (|| -> Result<()> {
        let mut file = OpenOptions::new().write(true).create_new(true).open(&tmp)?;
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
        file.write_all(b"{\"version\":1,\"entries\":{")?;
        for (i, id) in state.entries.keys().enumerate() {
            if i > 0 {
                file.write_all(b",")?;
            }
            serde_json::to_writer(&mut file, id)?;
            file.write_all(b":")?;
            serde_json::to_writer(
                &mut file,
                &managed(paths, state, id)?.ok_or("missing ownership record")?,
            )?;
        }
        file.write_all(b"}}")?;
        file.sync_all()?;
        fs::rename(&tmp, paths.state.join("state.json"))?;
        File::open(&paths.state)?.sync_all()?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}
fn owned(current: &Option<String>, m: &Managed) -> bool {
    current.as_ref() == Some(&m.generated) || current == &m.previous
}
fn restore_one(paths: &Paths, id: &str, m: &Managed) -> Result<()> {
    let target = paths.target(id);
    let current = read_optional(&target)?;
    if current == m.original {
        return Ok(());
    } // Previous run restored it before exiting.
    if !owned(&current, m) {
        return Err(format!(
            "{id}: manually changed or removed; refusing to overwrite (state kept at {})",
            paths.state.display()
        )
        .into());
    }
    if let Some(original) = &m.original {
        atomic(&target, original, m.original_mode.unwrap_or(0o600))?;
    } else {
        fs::remove_file(target)?;
    }
    Ok(())
}
fn sync(paths: &Paths, state: &mut State, dry: bool, gio: &Path) -> Result<()> {
    let apps = inventory(paths, state)?;
    let index = Index::new(&apps);
    let mut groups: BTreeMap<usize, Vec<Pin>> = BTreeMap::new();
    let mut skipped = 0;
    let file = match File::open(paths.data.join("recently-used.xbel")) {
        Ok(file) => Some(file),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    if let Some(file) = &file {
        let before = file.metadata()?;
        bookmarks(BufReader::new(file), |uri, name, exec, pin| {
            if let Some(i) = index.find(name, exec) {
                retain_pin(file, groups.entry(i).or_default(), uri, pin)?;
            } else {
                skipped += 1;
            }
            Ok(())
        })?;
        let after = file.metadata()?;
        if before.len() != after.len() || before.modified()? != after.modified()? {
            return Err("history changed during scan; leaving actions unchanged".into());
        }
    }
    let mut wanted = BTreeSet::new();
    let mut changed = 0;
    let mut conflicts = Vec::new();
    for (i, pins) in groups {
        let group = pins
            .into_iter()
            .map(|pin| {
                read_pin(
                    file.as_ref().expect("pins require an open history file"),
                    pin,
                )
            })
            .collect::<Result<Vec<_>>>()?;
        let app = &apps[i];
        wanted.insert(app.id.clone());
        let target = paths.target(&app.id);
        if target.is_symlink() {
            conflicts.push(app.id.clone());
            continue;
        }
        let current = read_optional(&target)?;
        let record = managed(paths, state, &app.id)?;
        if let Some(m) = &record {
            if !owned(&current, m) {
                conflicts.push(app.id.clone());
                continue;
            }
        } else if current.as_ref().is_some_and(|s| s.contains(MARKER)) {
            conflicts.push(app.id.clone());
            continue;
        }
        let text = app_text(app, record.as_ref())?;
        let generated = render(&text, &group, &target, gio)?;
        drop(text);
        if current.as_ref() == Some(&generated) {
            continue;
        }
        changed += 1;
        println!(
            "{} {} ({} recent items)",
            if dry { "Would update" } else { "Updating" },
            app.id,
            group.len()
        );
        if !dry {
            let original = record
                .as_ref()
                .map(|m| m.original.clone())
                .unwrap_or_else(|| current.clone());
            let original_mode = record.as_ref().and_then(|m| m.original_mode).or_else(|| {
                fs::metadata(&target)
                    .ok()
                    .map(|m| m.permissions().mode() & 0o777)
            });
            let record = Managed {
                original,
                original_mode,
                generated,
                previous: current,
            };
            // Journal one app, update the small ownership index if needed, then publish it.
            atomic(
                &record_path(paths, &app.id),
                &serde_json::to_string(&record)?,
                0o600,
            )?;
            if state
                .entries
                .insert(app.id.clone(), record.original.is_some())
                .is_none()
            {
                save(paths, state)?;
            }
            atomic(&target, &record.generated, 0o600)?;
        }
    }
    for id in state.entries.keys().cloned().collect::<Vec<_>>() {
        if wanted.contains(&id) {
            continue;
        }
        println!("{} {id}", if dry { "Would restore" } else { "Restoring" });
        let record = managed(paths, state, &id)?.ok_or("missing ownership record")?;
        if dry {
            let current = read_optional(&paths.target(&id))?;
            if current != record.original && !owned(&current, &record) {
                conflicts.push(id);
            }
        } else {
            if let Err(e) = restore_one(paths, &id, &record) {
                eprintln!("{e}");
                conflicts.push(id);
                continue;
            }
            forget(paths, state, &id)?;
        }
    }
    println!(
        "{} apps indexed; {changed} updates; {skipped} unmatched/ambiguous records skipped",
        apps.len()
    );
    if !conflicts.is_empty() {
        return Err(format!(
            "manual edits detected: {}; no conflicting file was overwritten",
            conflicts.join(", ")
        )
        .into());
    }
    Ok(())
}
fn which(name: &str) -> Result<PathBuf> {
    env::split_paths(&env::var_os("PATH").unwrap_or_default())
        .map(|p| p.join(name))
        .find(|p| p.is_file() && fs::metadata(p).is_ok_and(|m| m.permissions().mode() & 0o111 != 0))
        .ok_or_else(|| format!("required command missing: {name}").into())
}
fn run() -> Result<()> {
    let args: Vec<_> = env::args().skip(1).collect();
    if args == ["--version"] {
        println!(
            "xdg-recent-actions {} ({})",
            env!("CARGO_PKG_VERSION"),
            env!("GIT_REVISION")
        );
        return Ok(());
    }
    if args.is_empty() || args == ["--help"] {
        println!(
            "xdg-recent-actions {}\n\nUsage: xdg-recent-actions sync [--dry-run] | restore | check\n\nReads XDG_DATA_HOME/recently-used.xbel, adds up to eight recent Desktop Actions\nper app. Ambiguous matches are skipped. State: XDG_STATE_HOME/xdg-recent-actions.\ncheck is read-only; sync journals backups and refuses to overwrite manual edits.",
            env!("CARGO_PKG_VERSION")
        );
        return Ok(());
    }
    let command = args[0].as_str();
    if !matches!(command, "sync" | "restore" | "check" | "export-state-v1")
        || args.len() > 2
        || (args.len() == 2 && (command != "sync" || args[1] != "--dry-run"))
    {
        return Err("invalid arguments; use --help".into());
    }
    let paths = Paths::from_env()?;
    let dry = command == "check" || args.get(1).is_some_and(|s| s == "--dry-run");
    let _lock = if !dry {
        fs::create_dir_all(&paths.state)?;
        fs::set_permissions(&paths.state, fs::Permissions::from_mode(0o700))?;
        let lock = OpenOptions::new()
            .create(true)
            .truncate(false)
            .read(true)
            .write(true)
            .open(paths.state.join("lock"))?;
        lock.try_lock()
            .map_err(|e| format!("another sync/install is running: {e}"))?;
        Some(lock)
    } else {
        None
    };
    let mut state = load(&paths, dry)?;
    let start = Instant::now();
    if command == "export-state-v1" {
        export_v1(&paths, &state)?;
    } else if command == "restore" {
        for id in state.entries.keys().cloned().collect::<Vec<_>>() {
            let record = managed(&paths, &state, &id)?.ok_or("missing ownership record")?;
            restore_one(&paths, &id, &record)?;
            forget(&paths, &mut state, &id)?;
            println!("Restored {id}");
        }
    } else {
        sync(&paths, &mut state, dry, &which("gio")?)?;
    }
    println!(
        "Finished in {:.2} ms",
        start.elapsed().as_secs_f64() * 1000.0
    );
    Ok(())
}
fn main() {
    if let Err(e) = run() {
        eprintln!("xdg-recent-actions: {e}");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn matching_prefers_command_and_skips_ambiguity() {
        let app = |id: &str, exe: &str| App {
            id: id.into(),
            source: None,
            name: id.into(),
            executable: exe.into(),
        };
        let apps = vec![
            app("nemo.desktop", "nemo"),
            app("inkscape.desktop", "inkscape"),
            app("other.desktop", "inkscape"),
        ];
        let index = Index::new(&apps);
        assert_eq!(index.find("nemo", "'inkscape %F'"), None);
        assert_eq!(index.find("inkscape", "'inkscape %F'"), Some(1));
        assert_eq!(index.find("inkscape", "'nemo %U'"), Some(0));
    }
    #[test]
    fn generic_wrappers_require_an_application_identity() {
        let apps = vec![App {
            id: "org.example.App.desktop".into(),
            name: "Example".into(),
            executable: "flatpak".into(),
            source: None,
        }];
        let index = Index::new(&apps);
        assert_eq!(index.find("unknown", "flatpak run org.other.App %u"), None);
        assert_eq!(
            index.find("org.example.App", "flatpak run org.example.App %u"),
            Some(0)
        );
    }
    #[test]
    fn bounded_pins_match_full_sort_with_unsorted_duplicates() {
        let dir = tempfile::tempdir().unwrap();
        let item = dir.path().join("a & b");
        fs::write(&item, "").unwrap();
        let mut xml = String::from("<xbel>");
        let mut newest = BTreeMap::new();
        for n in 0..10_000 {
            let mut url = Url::from_file_path(&item).unwrap();
            url.set_fragment(Some(&format!("item{}", (n * 7919) % 137)));
            let uri = url.to_string();
            let modified = (n * 3571) % 997;
            newest
                .entry(uri.clone())
                .and_modify(|t: &mut i64| *t = (*t).max(modified))
                .or_insert(modified);
            let stamp = chrono::DateTime::from_timestamp(modified, 0)
                .unwrap()
                .to_rfc3339();
            xml.push_str(&format!(
                "<bookmark href=\"{}\"><application modified=\"{stamp}\"/></bookmark>",
                quick_xml::escape::escape(&uri)
            ));
        }
        xml.push_str("</xbel>");
        let history = dir.path().join("history");
        fs::write(&history, &xml).unwrap();
        let file = File::open(history).unwrap();
        let mut retained = Vec::new();
        bookmarks(BufReader::new(&file), |uri, _, _, pin| {
            retain_pin(&file, &mut retained, uri, pin)?;
            assert!(retained.len() <= LIMIT);
            Ok(())
        })
        .unwrap();
        let mut expected: Vec<_> = newest.into_iter().collect();
        expected.sort_by_key(|(uri, modified)| (std::cmp::Reverse(*modified), fingerprint(uri)));
        expected.truncate(LIMIT);
        let result = retained
            .into_iter()
            .map(|pin| {
                let r = read_pin(&file, pin).unwrap();
                (r.uri, pin.modified / 1_000_000)
            })
            .collect::<Vec<_>>();
        assert_eq!(result, expected);
        assert_eq!(std::mem::size_of::<Pin>(), 32);
    }
    #[test]
    fn malformed_xml_does_not_clear_history() {
        assert!(bookmarks("<xbel><bookmark>".as_bytes(), |_, _, _, _| Ok(())).is_err());
        assert!(bookmarks("not xml".as_bytes(), |_, _, _, _| Ok(())).is_err());
        assert!(bookmarks("<wrong/>".as_bytes(), |_, _, _, _| Ok(())).is_err());
        assert!(
            bookmarks("<xbel/>".as_bytes(), |_, _, _, _| panic!(
                "unexpected record"
            ))
            .is_ok()
        );
    }
    #[test]
    fn preserves_existing_sections_and_handles_action_collisions() {
        let text = "[Desktop Entry]\nName=Test\nType=Application\nExec=test %U\nActions=XdgRecent0;\n\n[Desktop Action XdgRecent0]\nName=Existing\nExec=test\n";
        let r = Recent {
            uri: "file:///tmp/a%20b".into(),
            path: "/tmp/a b".into(),
        };
        let out = render(
            text,
            &[r],
            Path::new("/tmp/test.desktop"),
            Path::new("/usr/bin/gio"),
        )
        .unwrap();
        assert!(out.contains("Actions=XdgRecent0;XdgRecent1;"));
        assert!(out.contains("Name=Existing\nExec=test"));
        assert!(out.contains("file:///tmp/a%%20b"));
        assert_eq!(exec_arg("a\"$`\\%"), "\"a\\\\\"\\\\$\\\\`\\\\\\\\%%\"");
    }
}
